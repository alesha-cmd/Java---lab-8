    private static int insertVisitor(Connection conn, Visitor v) throws SQLException{
        String checkSql = "SELECT id FROM study.visitors WHERE phone = ?";
        try(PreparedStatement ps = conn.prepareStatement(checkSql)){
            ps.setString(1, v.getPhone());
            ResultSet rs = ps.executeQuery();
            if (rs.next()) return rs.getInt("id");
        }
        String insertSql = "INSERT INTO study.visitors (name, surname, phone, subscribed) VALUES (?, ?, ?, ?)";
        try (PreparedStatement ps = conn.prepareStatement(insertSql, Statement.RETURN_GENERATED_KEYS)){
            ps.setString(1, v.getName());
            ps.setString(2, v.getSurname());
            ps.setString(3, v.getPhone());
            ps.setBoolean(4, v.isSubscribed());
            ps.executeUpdate();
            ResultSet keys = ps.getGeneratedKeys();
            keys.next();
            return keys.getInt(1);
        }
    }
    private static int insertBook(Connection conn, Book b) throws SQLException {
        // Уникальность проверяем по ISBN
        String checkSql = "SELECT id FROM study.books WHERE isbn = ?";
        try (PreparedStatement ps = conn.prepareStatement(checkSql)) {
            ps.setString(1, b.getIsbn());
            ResultSet rs = ps.executeQuery();
            if (rs.next()) return rs.getInt("id");
        }
        String insertSql = "INSERT INTO study.books (title, author, \"year\", isbn, publisher) VALUES (?, ?, ?, ?, ?)";
        try (PreparedStatement ps = conn.prepareStatement(insertSql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, b.getName());
            ps.setString(2, b.getAuthor());
            ps.setInt(3, b.getPublishingYear());
            ps.setString(4, b.getIsbn());
            ps.setString(5, b.getPublisher());
            ps.executeUpdate();
            ResultSet keys = ps.getGeneratedKeys();
            keys.next();
            return keys.getInt(1);
        }
    }
    private static void linkVisitorAndBook(Connection conn, int visitorId, int bookId) throws SQLException {
        String sql = "INSERT INTO study.visitor_books (visitor_id, book_id) VALUES (?, ?)";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, visitorId);
            ps.setInt(2, bookId);
            ps.executeUpdate();
        }
    }
